package sieve

import (
	"fmt"
	"strings"
	"time"
)

// Route represents a single sender → folder mapping
type Route struct {
	SenderEmail   string
	TargetMailbox string // mailbox name for display
	TargetPath    string // full Sieve path (e.g. "Family" or "Receipts.2026")
}

type SpamRule struct {
	JunkPath  string
	Threshold int
}

// Generate creates a complete Sieve script from routes and the screener mailbox name.
func Generate(routes []Route, screenerPath string, spamRule *SpamRule) string {
	var sb strings.Builder
	if spamRule != nil {
		sb.WriteString(`require ["fileinto", "spamtest", "relational", "comparator-i;ascii-numeric"];`)
	} else {
		sb.WriteString(`require ["fileinto"];`)
	}
	sb.WriteString("\n\n")
	sb.WriteString(fmt.Sprintf("# Generated by JMAP Screener at %s\n", time.Now().UTC().Format(time.RFC3339)))
	sb.WriteString(fmt.Sprintf("# %d known sender(s)\n\n", len(routes)))

	for _, r := range routes {
		sb.WriteString(fmt.Sprintf(
			`if address :is ["from", "sender"] "%s" { fileinto "%s"; stop; }`+"\n",
			escapeSieveString(r.SenderEmail),
			escapeSieveString(r.TargetPath),
		))
	}
	if spamRule != nil {
		sb.WriteString("\n# Spam: route unknown spam to Junk\n")
		sb.WriteString(fmt.Sprintf(
			`if spamtest :value "ge" :comparator "i;ascii-numeric" "%d" { fileinto "%s"; stop; }`+"\n",
			spamRule.Threshold,
			escapeSieveString(spamRule.JunkPath),
		))
	}

	sb.WriteString("\n# Default: route unknown senders to Screener\n")
	sb.WriteString(fmt.Sprintf(`fileinto "%s";`+"\n", escapeSieveString(screenerPath)))

	return sb.String()
}

// escapeSieveString escapes special characters in a Sieve string literal.
// In Sieve, only double-quote (") and backslash (\) need escaping inside double-quoted strings.
func escapeSieveString(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\") // backslash first
	s = strings.ReplaceAll(s, "\"", "\\\"") // then double quote
	return s
}

// BuildSievePath converts a JMAP display path to a Sieve fileinto path.
// Top-level mailboxes stay top-level; only the special Inbox name is normalized.
func BuildSievePath(name string) string {
	if strings.EqualFold(name, "inbox") {
		return "INBOX"
	}
	if len(name) > len("inbox.") && strings.EqualFold(name[:len("inbox.")], "inbox.") {
		return "INBOX" + name[len("inbox"):]
	}

	return name
}
