func TestGenerate_EmptyRoutes(t *testing.T) {
	output := Generate(nil, "INBOX.Screener", nil)

	if !strings.Contains(output, `require ["fileinto"];`) {
		t.Error("output missing require line")
	}
	if strings.Contains(output, "envelope") {
		t.Error("output should not require or use envelope")
	}
	if !strings.Contains(output, "# 0 known sender(s)") {
		t.Error("output missing 0 count comment")
	}
	if !strings.Contains(output, `fileinto "INBOX.Screener";`) {
		t.Error("output missing default fileinto")
	}
	if !strings.Contains(output, "# Generated by JMAP Screener at ") {
		t.Error("output missing timestamp comment")
	}
	if !strings.Contains(output, "# Default: route unknown senders to Screener") {
		t.Error("output missing default comment")
	}
}

