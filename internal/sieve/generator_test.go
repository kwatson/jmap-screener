func TestGenerate_MultipleRoutes(t *testing.T) {
	routes := []Route{
		{SenderEmail: "alice@x.com", TargetMailbox: "Alice", TargetPath: "INBOX.Alice"},
		{SenderEmail: "bob@x.com", TargetMailbox: "Bob", TargetPath: "INBOX.Bob"},
		{SenderEmail: "carol@x.com", TargetMailbox: "Carol", TargetPath: "INBOX.Carol"},
	}
	output := Generate(routes, "INBOX.Screener", nil)

	if !strings.Contains(output, `if address :is ["from", "sender"] "alice@x.com" { fileinto "INBOX.Alice"; stop; }`) {
		t.Error("output missing alice rule")
	}
	if !strings.Contains(output, `if address :is ["from", "sender"] "bob@x.com" { fileinto "INBOX.Bob"; stop; }`) {
		t.Error("output missing bob rule")
	}
	if !strings.Contains(output, `if address :is ["from", "sender"] "carol@x.com" { fileinto "INBOX.Carol"; stop; }`) {
		t.Error("output missing carol rule")
	}
	if !strings.Contains(output, "# 3 known sender(s)") {
		t.Error("output missing 3 count comment")
	}

	alicePos := strings.Index(output, "alice@x.com")
	bobPos := strings.Index(output, "bob@x.com")
	carolPos := strings.Index(output, "carol@x.com")
	if !(alicePos < bobPos && bobPos < carolPos) {
		t.Error("routes not in expected order")
	}
}

func TestGenerate_BackslashEscaping(t *testing.T) {
	routes := []Route{
		{SenderEmail: `bob\smith@x.com`, TargetMailbox: "Test", TargetPath: "INBOX.Test"},
	}
	output := Generate(routes, "INBOX.Screener", nil)

	if !strings.Contains(output, `bob\\smith@x.com`) {
		t.Errorf("backslash not escaped in output: %s", output)
	}
	if strings.Contains(output, `bob\smith`) && !strings.Contains(output, `bob\\smith`) {
		t.Error("unescaped backslash found in output")
	}
}

