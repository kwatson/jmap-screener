func TestGenerate_StopAfterFileinto(t *testing.T) {
	routes := []Route{
		{SenderEmail: "a@x.com", TargetMailbox: "A", TargetPath: "INBOX.A"},
		{SenderEmail: "b@x.com", TargetMailbox: "B", TargetPath: "INBOX.B"},
	}
	output := Generate(routes, "INBOX.Screener", nil)

	ruleLines := 0
	for _, line := range strings.Split(output, "\n") {
		if strings.Contains(line, "if address") && strings.Contains(line, "stop;") {
			ruleLines++
		}
	}
	if ruleLines != 2 {
		t.Errorf("expected 2 rules with stop;, got %d", ruleLines)
	}
}

