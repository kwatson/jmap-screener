func TestGenerate_SpamRuleAfterKnownRoutesBeforeDefault(t *testing.T) {
	routes := []Route{
		{SenderEmail: "sender@x.com", TargetMailbox: "Folder", TargetPath: "INBOX.Folder"},
	}
	output := Generate(routes, "INBOX.Screener", &SpamRule{JunkPath: "Junk Mail", Threshold: 5})

	if !strings.Contains(output, `require ["fileinto", "spamtest", "relational", "comparator-i;ascii-numeric"];`) {
		t.Error("output missing spamtest requirements")
	}
	spamRule := `if spamtest :value "ge" :comparator "i;ascii-numeric" "5" { fileinto "Junk Mail"; stop; }`
	if !strings.Contains(output, spamRule) {
		t.Fatalf("output missing spam rule: %s", output)
	}

	knownPos := strings.Index(output, "sender@x.com")
	spamPos := strings.Index(output, "if spamtest")
	defaultPos := strings.Index(output, `fileinto "INBOX.Screener";`)
	if !(knownPos < spamPos && spamPos < defaultPos) {
		t.Fatalf("rules not in expected order: known=%d spam=%d default=%d\n%s", knownPos, spamPos, defaultPos, output)
	}
}

